"""Write docs/level_design.md from the level files and their computed landscapes.

    python scripts/level_report.py

Run it after calibrate_levels.py so the design document always quotes the current numbers.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from checkpoint import engine, levels  # noqa: E402
from checkpoint.landscape import candidate_checks, load_or_build  # noqa: E402


def best(points, min_yield=0.0):
    ok = [p for p in points if p["yield"] >= min_yield - 1e-9]
    return max(ok, key=lambda p: p["fidelity"]) if ok else None


def main():
    out = [
        "# Level design",
        "",
        "Generated by `scripts/level_report.py` from `levels/*.json` and `data/landscapes/*.json`. Do not edit by hand.",
        "Every number is exact (Aer density matrix, readout applied analytically). \"Best\" is the best layout the",
        "landscape search found (all single checks plus pairs of the best singles and a seeded random sample), which is a",
        "strong heuristic optimum rather than a proof.",
        "",
        "| # | Title | Lesson | No checks (F) | Par (F / Y) | Best found (F / Y) | Goal (F / Y) | Layouts meeting goal | Legal single checks |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    details = []
    for lv in levels.all_levels():
        d = load_or_build(lv["id"])
        g = engine.effective_goal(lv["id"])
        pts = d["points"]
        b = best(pts)
        meet = sum(1 for p in pts if p["fidelity"] >= g["fidelity"] - 1e-9 and p["yield"] >= g["min_yield"] - 1e-9)
        par = d["par"]
        par_s = f"{par['metrics']['fidelity']:.3f} / {par['metrics']['yield']:.3f}" if par.get("available") else "n/a"
        out.append(
            f"| {lv['id']} | {lv['title']} | {lv.get('lesson', '')} | {d['baseline']['fidelity']:.3f} | {par_s} | "
            f"{b['fidelity']:.3f} / {b['yield']:.3f} | {g['fidelity']:.3f} / {g['min_yield']:.3f} | {meet} of {len(pts)} | {len(candidate_checks(lv))} |"
        )
        details += [
            f"## {lv['id']} {lv['title']}",
            "",
            f"**Brief.** {lv.get('brief', '')}",
            "",
            f"**Learning moment.** {lv.get('learning_moment', '')}",
            "",
            f"**Noise.** {d['noise']['label']} (p2 {d['noise']['p2']}, p1 {d['noise']['p1']}, idle {d['noise']['p_idle']}, readout {d['noise']['p_readout']}"
            + (f", bias {d['noise']['bias']}" if d['noise'].get('bias') else "") + ")."
            + (f" Slots limited to {lv['slots']}." if lv.get("slots") else ""),
            "",
            f"**Parts.** {', '.join(lv['parts']['paulis'])}; left edge up to {lv['parts']['max_weight']} qubits; {lv['budget']['ancillas']} ancilla(s). T count {lv['t_count']}.",
            "",
            f"**Example winning layout.** `{b['checks']}` gives fidelity {b['fidelity']:.4f} at yield {b['yield']:.4f}, cost {b['cost']}.",
            "",
        ]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "level_design.md").write_text("\n".join(out + [""] + details) + "\n", encoding="utf-8")
    print("wrote docs/level_design.md")


if __name__ == "__main__":
    main()
